    /// On Linux with nftables installed: the generated file is accepted by nft's own checker.
    #[cfg(target_os = "linux")]
    #[test]
    fn nft_accepts_the_rules() {
        if std::process::Command::new("nft").arg("--version").output().is_err() {
            return;
        }
        let cfg = Config::fresh();
        // The private users need not exist where the tests run: the grammar is what is checked.
        let mut rules = filter_rules(&cfg);
        for a in &cfg.apps {
            rules = rules.replace(&format!("meta skuid \"{}\"", a.os_user), "meta skuid 0");
        }
        let dir = tempfile::tempdir().unwrap();
        let p = dir.path().join("rules.nft");
        std::fs::write(&p, rules).unwrap();
        let out = std::process::Command::new("nft").arg("-c").arg("-f").arg(&p).output().unwrap();
        let err = String::from_utf8_lossy(&out.stderr);
        // Checking needs no special rights on most systems; where it does, that is not a rules error.
        assert!(out.status.success() || err.contains("Operation not permitted"), "{err}");
    }
