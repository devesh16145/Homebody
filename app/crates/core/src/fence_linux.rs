    #[test]
    fn every_protected_user_is_sent_to_a_chain_that_ends_in_refusal() {
        let cfg = Config::fresh();
        let rules = filter_rules(&cfg);
        assert!(rules.starts_with("# Homebody firewall rules."));
        // Loading the file replaces the whole table in one step.
        assert!(rules.contains("table inet homebody\ndelete table inet homebody\ntable inet homebody {"));
        for app in cfg.apps.iter().filter(|a| !a.windowed) {
            let c = chain(&app.os_user);
            assert!(rules.contains(&format!("meta skuid \"{}\" jump {c}\n", app.os_user)), "{}", app.id);
            let body = rules.split(&format!("chain {c} {{\n")).nth(1).unwrap().split("\t}\n").next().unwrap();
            let lines: Vec<&str> = body.lines().map(str::trim).collect();
            assert!(lines[0].starts_with("oifname \"lo\" tcp dport {") && lines[0].contains(&app.proxy_port.to_string()) && lines[0].ends_with("accept"));
            assert_eq!(lines[lines.len() - 1], "reject", "{}", app.id);
            assert_eq!(lines[lines.len() - 2], "meta l4proto tcp reject with tcp reset");
            // Nothing accepts traffic that leaves this computer.
            for l in lines.iter().filter(|l| l.ends_with("accept")) {
                assert!(l.starts_with("oifname \"lo\""), "{l}");
            }
            // Another app's gate is never among its open ports.
            for other in cfg.apps.iter().filter(|o| o.id != app.id) {
                assert!(!lines[0].contains(&format!(" {},", other.proxy_port)) && !lines[0].contains(&format!(" {} }}", other.proxy_port)), "{} can reach {}'s gate", app.id, other.id);
            }
        }
    }

    #[test]
    fn a_model_server_may_use_local_ports_but_never_another_gate() {
        let cfg = Config::fresh();
        let rules = filter_rules(&cfg);
        let ollama = cfg.app("ollama").unwrap();
        let body = rules.split(&format!("chain {} {{\n", chain(&ollama.os_user))).nth(1).unwrap().split("\t}\n").next().unwrap();
        let gates = body.find("tcp dport 47110-47139 reject with tcp reset").expect("gates closed");
        let any = body.find("oifname \"lo\" accept").expect("local ports open");
        assert!(gates < any, "the refusal has to come first");
        assert!(body.find(&ollama.proxy_port.to_string()).unwrap() < gates, "its own gate is allowed before that");
    }

