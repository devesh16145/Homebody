//! The fence on Linux. The same idea as on macOS, built from what Linux has:
//!
//! 1. **A private user per app** (`useradd --system`), in a group of its own. It cannot enter
//!    your home folder, and you start things as it through one `sudoers` line.
//! 2. **Firewall rules per user** (nftables, `meta skuid`). A protected user may open
//!    connections to its own gate on this computer and to nothing else: not another address, not
//!    another app's gate, not a name server. The rules are loaded by a small root service that
//!    also keeps them loaded.
//! 3. **No side doors for name lookups.** On Linux a program can ask the system's resolver to
//!    look a name up over a local socket, which the firewall never sees. The folders holding
//!    those sockets are closed to the protected group.
//!
//! A protected program is also started with "no new privileges", so a set-user-ID program
//! (`su`, `pkexec`, `ping`) gives it nothing.
//!
//! What this version does not do on Linux: windowed apps, and agents reaching servers they
//! started themselves (only the listed local ports, such as a local model's, are open).
//!
//! This file compiles on every Unix so its logic is checked wherever the tests run; it is only
//! ever *used* on Linux (see the dispatch in `fence`).

use crate::config::{AppConfig, Config};
use crate::fence::{Health, Violation, GROUP};
use crate::model::SetupResult;
use std::time::Duration;

pub const SYSTEM_DIR: &str = "/var/lib/homebody";
pub const WORKSPACE_ROOT: &str = "/var/lib/homebody/work";
pub const FILTER_STATUS: &str = "/run/homebody.fence";
pub const RULES_FILE: &str = "/etc/homebody/rules.nft";
const DROP_TAG: &str = "homebody-drop:";
/// Where the health check knocks (see `filter_rules`). Homebody listens here; no app may reach it.
pub const PROBE_PORT: u16 = 47199;

/// When each app's health check last tried a name lookup. The refusal of that lookup is ours,
/// not the app's, and must not appear in Activity as something the app did.
static PROBED: std::sync::Mutex<Vec<(String, std::time::Instant)>> = std::sync::Mutex::new(Vec::new());

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

pub fn home_for(os_user: &str) -> String {
    format!("{SYSTEM_DIR}/home/{}", os_user.trim_start_matches("_hb").trim_start_matches('_'))
}

/// Where the real user keeps things protected apps may read (the inspection certificate).
pub fn shared_dir(real_user: &str) -> String {
    format!("{SYSTEM_DIR}/shared/{real_user}")
}

/// A chain name for an app's user: letters, digits and underscores only.
fn chain(os_user: &str) -> String {
    format!("u{}", os_user.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '_').collect::<String>())
}

/// nftables rules for every protected app, as one file that replaces the table in one step.
pub fn filter_rules(cfg: &Config) -> String {
    let (lo, hi) = (crate::catalog::GATE_PORTS.start(), crate::catalog::GATE_PORTS.end());
    let apps: Vec<&AppConfig> = cfg.apps.iter().filter(|a| !a.windowed).collect();
    let mut s = String::from("# Homebody firewall rules. Generated by the app; changes are overwritten.\ntable inet homebody\ndelete table inet homebody\ntable inet homebody {\n\tchain out {\n\t\ttype filter hook output priority filter; policy accept;\n");
    for app in &apps {
        s.push_str(&format!("\t\tmeta skuid \"{}\" jump {}\n", app.os_user, chain(&app.os_user)));
    }
    s.push_str("\t}\n");
    for app in &apps {
        let mut ports: Vec<u16> = vec![app.proxy_port];
        ports.extend(&app.local_ports);
        let list = ports.iter().map(u16::to_string).collect::<Vec<_>>().join(", ");
        s.push_str(&format!("\n\t# {}\n\tchain {} {{\n", app.name.replace('\n', " "), chain(&app.os_user)));
        // Its own gate, and the local services it is meant to use.
        s.push_str(&format!("\t\toifname \"lo\" tcp dport {{ {list} }} accept\n"));
        // The health check connects here, where Homebody itself listens, to see that it is
        // refused. That is our own test, not the app's doing, so it is not written to the log.
        s.push_str(&format!("\t\toifname \"lo\" tcp dport {PROBE_PORT} reject with tcp reset\n"));
        // Answers to connections somebody on this computer made to a server it runs.
        s.push_str("\t\toifname \"lo\" ct state established,related accept\n");
        if app.loopback_all {
            // A model server talks to its own helpers on any local port, never to another gate.
            s.push_str(&format!("\t\toifname \"lo\" tcp dport {lo}-{hi} reject with tcp reset\n"));
            s.push_str("\t\toifname \"lo\" accept\n");
        }
        // Everything else is refused at once (so programs fail fast instead of waiting), and
        // a few a minute are written to the kernel log so they can be shown in Activity.
        s.push_str(&format!("\t\tlimit rate 20/minute burst 10 packets log prefix \"{DROP_TAG}{} \"\n", app.id));
        s.push_str("\t\tmeta l4proto tcp reject with tcp reset\n");
        s.push_str("\t\treject\n\t}\n");
    }
    s.push_str("}\n");
    s
}

const WATCHDOG: &str = r#"#!/bin/bash
# Homebody fence watchdog. Runs as root from systemd and keeps the firewall rules loaded and the
# resolver's local sockets closed to protected apps, including after restarts.
RULES=/etc/homebody/rules.nft
STATUS=/run/homebody.fence
GROUP=_homebody
USERS="@USERS@"
CLOSED="/run/systemd/resolve /run/nscd /var/run/nscd /run/dbus @REAL_HOME@"

ensure() {
  want=$(grep -c 'jump u' "$RULES" 2>/dev/null); want=${want:-0}
  have=$(nft list chain inet homebody out 2>/dev/null | grep -c 'jump u')
  if [ "$have" -lt "$want" ]; then
    nft -f "$RULES" 2>"$STATUS.err"
    have=$(nft list chain inet homebody out 2>/dev/null | grep -c 'jump u')
  fi
  for d in $CLOSED; do
    [ -d "$d" ] && setfacl -m "g:$GROUP:---" "$d" 2>/dev/null
  done
  state=down
  if [ "$want" -gt 0 ] && [ "$have" -ge "$want" ]; then state=ok; fi
  echo "$state $(date +%s) $USERS" > "$STATUS.tmp" && chmod 644 "$STATUS.tmp" && mv "$STATUS.tmp" "$STATUS"
}

if [ "${1:-}" = "--once" ]; then ensure; cat "$STATUS"; exit 0; fi
while true; do ensure; sleep 20; done
"#;

const UNIT: &str = r#"[Unit]
Description=Homebody fence: keeps protected AI apps' firewall rules loaded
After=network-pre.target nftables.service
Wants=network-pre.target

[Service]
ExecStart=/bin/bash /var/lib/homebody/fence-watchdog.sh
Restart=always
RestartSec=2

[Install]
WantedBy=multi-user.target
"#;

/// The script an administrator runs once. Idempotent: running it again repairs and updates.
pub fn setup_script(cfg: &Config, real_user: &str, real_home: &str) -> String {
    let apps: Vec<&AppConfig> = cfg.apps.iter().filter(|a| !a.windowed).collect();
    let users: Vec<&str> = apps.iter().map(|a| a.os_user.as_str()).collect();
    let mut s = String::from("#!/bin/bash\n# Homebody one-time setup for Linux. Generated by the app. Safe to run again.\nset -Eeuo pipefail\n");
    s.push_str(&format!("REAL_USER={}\nREAL_HOME={}\nGROUP={GROUP}\nSUPPORT={SYSTEM_DIR}\nWORKROOT={WORKSPACE_ROOT}\n", sh_quote(real_user), sh_quote(real_home)));
    s.push_str(r#"
STEP="starting"
trap 'echo "Setup stopped at: $STEP (while running: $BASH_COMMAND)" >&2' ERR
[ "$(id -u)" = 0 ] || { echo "Setup has to run as the administrator: homebody setup --print | sudo bash" >&2; exit 1; }

STEP="checking what this system has"
for tool in nft:nftables setfacl:acl sudo:sudo setpriv:util-linux useradd:shadow systemctl:systemd visudo:sudo; do
  command -v "${tool%%:*}" >/dev/null 2>&1 || { echo "Homebody needs the program '${tool%%:*}' (package '${tool##*:}'). Install it and run setup again." >&2; exit 1; }
done
id -u "$REAL_USER" >/dev/null 2>&1 || { echo "There is no user called $REAL_USER on this computer." >&2; exit 1; }

STEP="system folders"
mkdir -p "$SUPPORT" "$WORKROOT" "$SUPPORT/home" "$SUPPORT/shared" /etc/homebody
chown root:root "$SUPPORT" "$WORKROOT" "$SUPPORT/home" "$SUPPORT/shared" /etc/homebody
chmod 755 "$SUPPORT" "$WORKROOT" "$SUPPORT/home" "$SUPPORT/shared" /etc/homebody
# Yours: where the app puts what protected apps may read (the certificate for Look inside).
mkdir -p "$SUPPORT/shared/$REAL_USER"
chown "$REAL_USER" "$SUPPORT/shared/$REAL_USER"; chmod 755 "$SUPPORT/shared/$REAL_USER"

# 1. A group of its own, so protected apps share nothing with your own groups.
STEP="group for protected apps"
getent group "$GROUP" >/dev/null || groupadd --system "$GROUP"

ensure_user() { # name home
  local u="$1" home="$2"
  STEP="private space for $u"
  if ! id -u "$u" >/dev/null 2>&1; then
    useradd --system --gid "$GROUP" --home-dir "$home" --no-create-home --shell /bin/bash "$u" 2>/dev/null \
      || useradd --badname --system --gid "$GROUP" --home-dir "$home" --no-create-home --shell /bin/bash "$u"
  fi
  [ "$(id -gn "$u")" = "$GROUP" ] || usermod -g "$GROUP" "$u"
  passwd -l "$u" >/dev/null 2>&1 || true
  mkdir -p "$home"
  chown "$u:$GROUP" "$home"
  chmod 700 "$home"
}

ensure_workspace() { # dir owner
  local d="$1" u="$2"
  STEP="workspace folder $d"
  mkdir -p "$d"
  chown "$u:$GROUP" "$d"; chmod 2770 "$d"
  # You and the app can both read and change everything in it, including what the other makes.
  setfacl -m "u:$REAL_USER:rwx,u:$u:rwx" "$d"
  setfacl -d -m "u:$REAL_USER:rwx,u:$u:rwx,g::rwx,o::---" "$d"
  # The note is written AS the protected user, never as root: the folder is that user's, so a
  # link planted under this name must not be followed with root's rights.
  setpriv --reuid "$u" --regid "$GROUP" --clear-groups /bin/sh -c 'umask 007; cd "$1" && { [ -e README.txt ] || [ -L README.txt ] || printf "This folder is the only place the protected app can write.\nPut the files you want it to work on here.\n" > README.txt; }' sh "$d" 2>/dev/null || true
}

"#);
    for app in &apps {
        s.push_str(&format!("ensure_user {} {}\n", sh_quote(&app.os_user), sh_quote(&home_for(&app.os_user))));
        if let Some(w) = &app.workspace {
            s.push_str(&format!("ensure_workspace {} {}\n", sh_quote(w), sh_quote(&app.os_user)));
        }
    }
    s.push_str(r#"
# Your home folder stays closed to protected apps whatever its permissions are. Only this one
# entry is added to it; nothing else about it is changed.
STEP="keeping protected apps out of your home folder"
[ -d "$REAL_HOME" ] && setfacl -m "g:$GROUP:---" "$REAL_HOME"

# 2. Firewall rules, and a service that keeps them loaded across restarts.
STEP="firewall rules"
"#);
    s.push_str(&format!("cat > {RULES_FILE} <<'HB_EOF'\n{}HB_EOF\nchmod 644 {RULES_FILE}\n", filter_rules(cfg)));
    s.push_str(&format!("cat > \"$SUPPORT/fence-watchdog.sh\" <<'HB_EOF'\n{}HB_EOF\n", WATCHDOG.replace("@USERS@", &users.join(",")).replace("@REAL_HOME@", &real_home.replace(['"', '\'', ' ', '$', '`', '\\'], ""))));
    s.push_str("chown root:root \"$SUPPORT/fence-watchdog.sh\"; chmod 755 \"$SUPPORT/fence-watchdog.sh\"\n");
    s.push_str(&format!("cat > /etc/systemd/system/homebody-fence.service <<'HB_EOF'\n{UNIT}HB_EOF\n"));
    s.push_str(&format!(
        r#"nft -f {RULES_FILE}
STEP="starting the service that keeps the rules loaded"
systemctl daemon-reload
systemctl enable homebody-fence.service >/dev/null 2>&1 || true
systemctl restart homebody-fence.service

# 3. Let the app start things as the protected users without asking for a password each time.
STEP="permission to start protected apps"
# The second line gives anything started as a protected user a terminal of its own, so it
# cannot type into yours.
printf '%s ALL=({0}) NOPASSWD: ALL\nDefaults>{0} use_pty\n' "$REAL_USER" > /etc/sudoers.d/homebody.tmp
chmod 440 /etc/sudoers.d/homebody.tmp
if visudo -cf /etc/sudoers.d/homebody.tmp >/dev/null; then mv /etc/sudoers.d/homebody.tmp /etc/sudoers.d/homebody; else rm -f /etc/sudoers.d/homebody.tmp; echo "could not write the permission file" >&2; exit 1; fi

# 4. Confirm.
STEP="confirming the rules are loaded"
state="$(/bin/bash "$SUPPORT/fence-watchdog.sh" --once)"
case "$state" in
  ok*) echo "$state" ;;
  *) echo "The firewall rules did not load: $(tail -3 {FILTER_STATUS}.err 2>/dev/null | tr '\n' ' ')" >&2; false ;;
esac
"#,
        users.join(",")
    ));
    s
}

pub fn remove_script() -> String {
    format!(
        r#"#!/bin/bash
# Homebody: remove everything setup created. Workspace folders are kept.
set -uo pipefail
systemctl disable --now homebody-fence.service 2>/dev/null || true
rm -f /etc/systemd/system/homebody-fence.service /etc/sudoers.d/homebody {RULES_FILE} {FILTER_STATUS} {FILTER_STATUS}.err
systemctl daemon-reload 2>/dev/null || true
nft delete table inet homebody 2>/dev/null || true
for u in $(getent passwd | cut -d: -f1 | grep -E '^_hb'); do
  pkill -KILL -u "$u" 2>/dev/null || true
  userdel "$u" 2>/dev/null || true
done
for d in /run/systemd/resolve /run/nscd /var/run/nscd /run/dbus /home/*; do
  [ -d "$d" ] && setfacl -x "g:{GROUP}" "$d" 2>/dev/null || true
done
groupdel {GROUP} 2>/dev/null || true
rm -rf {SYSTEM_DIR}/home {SYSTEM_DIR}/fence-watchdog.sh
echo removed
"#
    )
}

/// The full command line that runs `program` protected: as the app's private user, with no way
/// to gain privileges, a clean environment, in `cwd`.
pub fn fenced_argv(app: &AppConfig, program: &str, args: &[String], env: &[(String, String)], cwd: Option<&str>) -> Vec<String> {
    let mut v: Vec<String> = ["/usr/bin/sudo", "-n", "-u", app.os_user.as_str(), "-H", "/usr/bin/setpriv", "--no-new-privs", "/usr/bin/env", "-i"].iter().map(|s| s.to_string()).collect();
    v.extend(env.iter().map(|(k, val)| format!("{k}={val}")));
    let dir = cwd.map(str::to_string).or_else(|| app.workspace.clone()).unwrap_or_else(|| home_for(&app.os_user));
    // Files it makes are writable by its group and, through the folder's defaults, by you.
    v.extend(["/bin/sh".into(), "-c".into(), "umask 002; cd \"$1\" && shift && exec \"$@\"".into(), "sh".into(), dir, program.to_string()]);
    v.extend(args.iter().cloned());
    v
}

async fn run(argv: Vec<String>, timeout: Duration) -> Option<(bool, String)> {
    let mut cmd = tokio::process::Command::new(&argv[0]);
    cmd.args(&argv[1..]).current_dir("/").stdin(std::process::Stdio::null()).stdout(std::process::Stdio::piped()).stderr(std::process::Stdio::piped()).kill_on_drop(true);
    let out = tokio::time::timeout(timeout, cmd.output()).await.ok()?.ok()?;
    let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    Some((out.status.success(), text))
}

fn strs(a: &[&str]) -> Vec<String> {
    a.iter().map(|s| s.to_string()).collect()
}

/// The rules tested for real, as the protected user: a harmless command runs; a connection to
/// another app's gate, where something really is listening, is refused (which reads the same
/// online or offline); and a name lookup through the system fails.
async fn holds(app: &AppConfig, probe_listening: bool, env: &[(String, String)]) -> bool {
    let t = Duration::from_secs(8);
    let wrap = |script: &str| fenced_argv(app, "/bin/bash", &strs(&["-c", script]), env, Some("/"));
    let Some((true, _)) = run(wrap("true"), t).await else { return false };
    // Something really is listening on the probe port (Homebody itself), so a refusal there
    // is the rules at work, online or offline. Without that listener, fall back to an address.
    let target = if probe_listening { format!("127.0.0.1/{PROBE_PORT}") } else { "1.1.1.1/443".to_string() };
    let direct = run(wrap(&format!("exec 3<>/dev/tcp/{target}")), t).await;
    let refused = matches!(direct, Some((false, _)));
    {
        let mut probed = PROBED.lock().unwrap();
        probed.retain(|(id, _)| id != &app.id);
        probed.push((app.id.clone(), std::time::Instant::now()));
    }
    let lookup = run(wrap("getent hosts example.com"), t).await;
    let no_lookup = matches!(lookup, Some((false, _)));
    refused && no_lookup
}

fn filter_status_ok(os_user: &str) -> bool {
    let Ok(text) = std::fs::read_to_string(FILTER_STATUS) else { return false };
    let mut parts = text.split_whitespace();
    let (Some(state), Some(epoch), Some(users)) = (parts.next(), parts.next(), parts.next()) else { return false };
    let fresh = epoch.parse::<i64>().map(|e| (chrono::Utc::now().timestamp() - e).abs() <= 90).unwrap_or(false);
    state == "ok" && fresh && users.split(',').any(|u| u == os_user)
}

/// Check every layer for one app.
pub async fn probe(app: &AppConfig, expected_rules: &str, probe_listening: bool, env: &[(String, String)]) -> Health {
    let t = Duration::from_secs(6);
    let mut h = Health { checked: true, ..Default::default() };
    h.installed = crate::catalog::find_binary(&app.binary).is_some();
    if app.windowed {
        return h; // not on Linux yet: stays "not installed"
    }
    h.user_exists = run(strs(&["id", "-u", &app.os_user]), t).await.map(|r| r.0).unwrap_or(false);
    if !h.user_exists {
        return h;
    }
    h.group_ok = run(strs(&["id", "-gn", &app.os_user]), t).await.map(|(ok, out)| ok && out.trim() == GROUP).unwrap_or(false);
    h.can_run = run(strs(&["/usr/bin/sudo", "-n", "-u", &app.os_user, "true"]), t).await.map(|r| r.0).unwrap_or(false);
    h.workspace_ok = app.workspace.as_ref().map(|w| std::path::Path::new(w).is_dir()).unwrap_or(true);
    if h.can_run {
        h.seatbelt_ok = holds(app, probe_listening, env).await;
    }
    h.filter_ok = filter_status_ok(&app.os_user);
    h.rules_current = std::fs::read_to_string(RULES_FILE).map(|installed| installed.trim() == expected_rules.trim()).unwrap_or(false);
    h
}

pub async fn stop_all(app: &AppConfig) {
    let _ = run(strs(&["/usr/bin/sudo", "-n", "-u", &app.os_user, "/bin/sh", "-c", "kill -TERM -1"]), Duration::from_secs(5)).await;
}

/// Follow the kernel log for packets the rules refused.
pub fn violation_stream() -> std::io::Result<tokio::process::Child> {
    tokio::process::Command::new("journalctl")
        .args(["-k", "-f", "-n", "0", "-o", "cat"])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .kill_on_drop(true)
        .spawn()
}

/// One refused packet as the kernel logs it, for example:
///
/// ```text
/// homebody-drop:claude-code IN= OUT=eth0 SRC=10.0.0.5 DST=1.1.1.1 LEN=60 ... PROTO=TCP SPT=40312 DPT=443 ...
/// ```
pub fn violation_in(line: &str) -> Option<Violation> {
    let rest = &line[line.find(DROP_TAG)? + DROP_TAG.len()..];
    let (app, fields) = rest.split_once(' ')?;
    if app.is_empty() || !app.chars().all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_') {
        return None;
    }
    let field = |name: &str| fields.split_whitespace().find_map(|f| f.strip_prefix(name));
    let port = field("DPT=").and_then(|p| p.parse::<u16>().ok()).unwrap_or(0);
    let local = field("OUT=") == Some("lo");
    let what = if port == 53 || port == 853 || port == 5353 {
        // The health check's own lookup, refused a moment ago: not the app's doing.
        if PROBED.lock().unwrap().iter().any(|(id, at)| id == app && at.elapsed() < Duration::from_secs(6)) {
            return None;
        }
        "lookup"
    } else if local && crate::catalog::GATE_PORTS.contains(&port) {
        "gate"
    } else {
        "direct"
    };
    Some(Violation { app: app.to_string(), process: String::new(), what, port, count: 1 })
}

/// Ask for the administrator's approval and run the script: a desktop password prompt where
/// there is one, otherwise a sentence saying what to run in a terminal.
pub async fn run_as_admin(script: &str, name: &str) -> SetupResult {
    let has_prompt = std::env::var("DISPLAY").is_ok() || std::env::var("WAYLAND_DISPLAY").is_ok();
    let pkexec = ["/usr/bin/pkexec", "/bin/pkexec"].into_iter().find(|p| std::path::Path::new(p).is_file());
    let (Some(pkexec), true) = (pkexec, has_prompt) else {
        return SetupResult { ok: false, message: "Run this once in a terminal, then try again:  homebody setup --print | sudo bash".into() };
    };
    let dir = match crate::paths::ensure_data_dir() {
        Ok(d) => d.join("run"),
        Err(e) => return SetupResult { ok: false, message: format!("Could not prepare setup: {e}") },
    };
    let _ = std::fs::create_dir_all(&dir);
    let path = dir.join(name);
    if let Err(e) = std::fs::write(&path, script) {
        return SetupResult { ok: false, message: format!("Could not prepare setup: {e}") };
    }
    let out = run(strs(&[pkexec, "/bin/bash", &path.to_string_lossy()]), Duration::from_secs(300)).await;
    let _ = std::fs::remove_file(&path);
    if let Some((ok, text)) = &out {
        let logs = crate::paths::logs_dir();
        let _ = std::fs::create_dir_all(&logs);
        let _ = std::fs::write(logs.join(format!("{name}.last.log")), format!("{} {}\n{}\n", crate::now_iso(), if *ok { "finished" } else { "failed" }, text));
    }
    match out {
        Some((true, _)) => SetupResult { ok: true, message: "Done.".into() },
        Some((false, text)) if text.contains("dismissed") || text.contains("Not authorized") => SetupResult { ok: false, message: "You cancelled the approval, so nothing was changed.".into() },
        Some((false, text)) => {
            let line = text.lines().rev().find(|l| l.contains("Setup stopped at:") || l.contains("Homebody needs")).unwrap_or_else(|| text.lines().last().unwrap_or("")).trim().to_string();
            SetupResult { ok: false, message: format!("Setup did not finish. {line}") }
        }
        None => SetupResult { ok: false, message: "Setup timed out waiting for approval.".into() },
    }
}

/// The certificate authorities this system trusts, as one PEM file's worth of text.
pub fn system_roots_pem() -> String {
    ["/etc/ssl/certs/ca-certificates.crt", "/etc/pki/tls/certs/ca-bundle.crt", "/etc/ssl/ca-bundle.pem", "/etc/ssl/cert.pem"].iter().find_map(|p| std::fs::read_to_string(p).ok()).unwrap_or_default()
}

